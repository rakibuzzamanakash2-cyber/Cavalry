import type { Metadata } from "next";
import Link from "next/link";
import { PageHeader, SectionHeading } from "@/components/page-header";
import { StageTracker } from "@/components/stage-tracker";
import { researchAreas } from "@/content/research";
import { getPublicProgrammes } from "@/data/programmes";

export const metadata: Metadata = {
  title: "Research",
  description:
    "CAVALRY research programmes and research areas: public finance, climate and disaster risk, causal inference and machine learning for policy.",
};

const process = [
  { name: "Protocol", detail: "The question, estimands and analysis plan are written down first." },
  { name: "Data audit", detail: "Every source is checked for coverage before the scope is fixed." },
  { name: "Dataset", detail: "A versioned dataset that rebuilds from raw data with one command." },
  { name: "Analysis", detail: "Estimates, robustness and uncertainty, all generated by code." },
  { name: "Publication", detail: "Paper, open code and a replication package." },
];

export default async function ResearchPage() {
  const programmes = await getPublicProgrammes();
  return (
    <div className="mx-auto w-full max-w-6xl px-4 pb-16 sm:px-6">
      <PageHeader eyebrow="Research" title="Questions worth answering carefully">
        We work on a small number of programmes at a time, each built around one clear question, a
        written protocol and data we can defend. Programmes are shared here once they are complete.
      </PageHeader>

      <section aria-labelledby="programmes" className="py-10 sm:py-14">
        <SectionHeading number="01" id="programmes">
          Completed programmes
        </SectionHeading>
        {programmes.length === 0 ? (
          <div className="border-line bg-sand/40 mt-6 border p-5 sm:p-6">
            <p className="font-serif text-xl">No completed programmes yet.</p>
            <p className="text-muted mt-2 max-w-2xl leading-relaxed">
              Our research stays confidential while it is in progress. Each programme is published
              here, with its methods and outputs, once it is finished.
            </p>
          </div>
        ) : null}
        <ul className="mt-6 grid gap-6">
          {programmes.map((p) => (
            <li key={p.slug}>
              <article className="border-line bg-surface grid gap-6 border p-5 shadow-[6px_6px_0_0_var(--color-sand)] sm:p-7 md:grid-cols-12">
                <div className="md:col-span-8">
                  <div className="tracking-caps flex flex-wrap items-center gap-x-4 gap-y-1 text-xs uppercase">
                    <span className="text-accent-strong">{p.label}</span>
                    <span className="text-muted flex items-center gap-2">
                      <span className="bg-accent inline-block size-2 rounded-full" aria-hidden />
                      {p.status}
                    </span>
                  </div>
                  <h3 className="mt-3 text-2xl leading-tight sm:text-3xl">
                    <Link
                      href={`/research/${p.slug}`}
                      className="hover:text-accent transition-colors"
                    >
                      {p.title}
                    </Link>
                  </h3>
                  <p className="text-muted mt-3 max-w-2xl leading-relaxed">{p.summary}</p>
                  <ul className="mt-4 flex flex-wrap gap-2" aria-label="Research areas">
                    {p.areas.map((a) => (
                      <li key={a} className="border-line text-muted border px-2.5 py-1 text-xs">
                        {a}
                      </li>
                    ))}
                  </ul>
                </div>
                <div className="flex flex-col justify-between gap-6 md:col-span-4">
                  <StageTracker stages={p.stages.map((s) => s.name)} current={p.currentStage} />
                  <Link
                    href={`/research/${p.slug}`}
                    className="bg-primary text-primary-foreground hover:bg-accent tracking-caps px-5 py-3.5 text-center text-xs uppercase transition-colors"
                  >
                    Read the programme
                  </Link>
                </div>
              </article>
            </li>
          ))}
        </ul>
      </section>

      <section aria-labelledby="areas" className="border-line border-t py-10 sm:py-14">
        <SectionHeading number="02" id="areas">
          Research areas
        </SectionHeading>
        <ul className="border-line mt-6 grid border-t border-l sm:grid-cols-2">
          {researchAreas.map((area) => (
            <li key={area.title} className="border-line border-r border-b p-5 sm:p-6">
              <h3 className="text-xl">{area.title}</h3>
              <p className="text-muted mt-2 leading-relaxed">{area.long}</p>
            </li>
          ))}
        </ul>
      </section>

      <section aria-labelledby="process" className="border-line border-t py-10 sm:py-14">
        <SectionHeading number="03" id="process">
          How every programme runs
        </SectionHeading>
        <p className="text-muted mt-3 max-w-3xl leading-relaxed">
          Each programme moves through the same evidence-gated stages. A stage is finished only when
          its output exists and has been reviewed — not when a date arrives.
        </p>
        <ol className="mt-6 grid gap-4 sm:grid-cols-2 lg:grid-cols-5">
          {process.map((step, i) => (
            <li key={step.name} className="border-line border-t-2 pt-3">
              <p className="text-accent font-serif text-2xl leading-none">{i + 1}</p>
              <h3 className="mt-2 text-lg">{step.name}</h3>
              <p className="text-muted mt-1 text-sm leading-relaxed">{step.detail}</p>
            </li>
          ))}
        </ol>
      </section>
    </div>
  );
}
