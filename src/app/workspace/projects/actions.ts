// Every action re-checks permissions on the server. Forms only send ids.

export type ActionState = {
  ok: boolean;
  message: string;
  errors?: Partial<Record<string, string>>;
  inviteLink?: string;
} | null;

const roleText = z
  .string()
  .trim()
  .min(2, "Give the role a name (at least 2 characters).")
  .max(60, "Keep the role under 60 characters.");

const DEFAULT_STAGES = [
  { name: "Protocol", detail: "Questions, estimands and analysis plan written and reviewed." },
  { name: "Data audit", detail: "Coverage of every source checked; scope decided." },
  { name: "Dataset", detail: "Versioned dataset rebuilt from raw data by one command." },
  { name: "Analysis", detail: "Estimates, robustness and uncertainty, generated by code." },
  { name: "Paper", detail: "Working paper, feedback, preprint and submission." },
];

/** A uuid from the form, or "" (ids are uuid columns: bad input must not reach the query). */
function formId(formData: FormData, key: string) {
  const value = String(formData.get(key) ?? "");
  return z.uuid().safeParse(value).success ? value : "";
}

function fieldErrors(issues: z.core.$ZodIssue[]) {
  const errors: Record<string, string> = {};
  for (const i of issues) errors[String(i.path[0])] ??= i.message;
  return errors;
}

const newProjectSchema = z.object({
  title: z.string().trim().min(5, "At least 5 characters.").max(140, "Under 140 characters."),
  summary: z.string().trim().min(20, "At least 20 characters.").max(600, "Under 600 characters."),
  question: z.string().trim().min(20, "At least 20 characters.").max(600, "Under 600 characters."),
  role: roleText,
});

/** Any member can open a project and becomes its leader. */
export async function createProject(_prev: ActionState, formData: FormData): Promise<ActionState> {
  const user = await requireMember("/workspace/projects/new");
  const parsed = newProjectSchema.safeParse(Object.fromEntries(formData));
  if (!parsed.success) {
    return {
      ok: false,
      message: "Please fix the highlighted fields.",
      errors: fieldErrors(parsed.error.issues),
    };
  }
  const { title, summary, question, role } = parsed.data;

  const db = getDb();
  // "new" is the create page's own URL.
  const base = slugify(title, "project") === "new" ? "new-project" : slugify(title, "project");
  let slug = base;
  for (let n = 2; await db.project.findUnique({ where: { slug }, select: { id: true } }); n++) {
    slug = `${base}-${n}`;
  }
  const number = String((await db.project.count()) + 1).padStart(2, "0");

  await db.$transaction(async (tx) => {
    const project = await tx.project.create({
      data: {
        slug,
        number,
        label: `Programme ${number}`,
        title,
        summary,
        question,
        status: "planning",
        statusLabel: "In progress",
        currentStage: 0,
        leads: [user.name],
        areas: [],
        whyItMatters: [],
        subQuestions: [],
        design: [],
        dataSources: [],
        approach: [],
        scopes: [],
        stages: DEFAULT_STAGES,
        outputs: [],
        commitments: [],
        highlights: [],
        lastUpdated: new Date(new Date().toISOString().slice(0, 10)),
        leaderId: user.id,
      },
    });
    await tx.projectMembership.create({
      data: { projectId: project.id, userId: user.id, role },
    });
  });

  redirect(`/workspace/projects/${slug}`);
}

type Check =
  | { allowed: false; error: string }
  | { allowed: true; access: NonNullable<Awaited<ReturnType<typeof getProjectAccessById>>> };

/** Leader, co-leader or admin (the research plan can be edited by co-leaders too). */
async function requireTeamRunner(projectId: string): Promise<Check> {
  if (!projectId) return { allowed: false, error: "Project not found." };
  const access = await getProjectAccessById(projectId);
  if (!access) return { allowed: false, error: "Project not found." };
  if (!access.canRunTeam) {
    return { allowed: false, error: "Only the leader, a co-leader or an admin can do that." };
  }
  return { allowed: true, access };
}

/** Save a project's research content. Leader, co-leader or admin. */
export async function updateProjectContent(
  _prev: ActionState,
  formData: FormData,
): Promise<ActionState> {
  const projectId = formId(formData, "projectId");
  const check = await requireTeamRunner(projectId);
  if (!check.allowed) return { ok: false, message: check.error };

  let raw: unknown;
  try {
    raw = JSON.parse(String(formData.get("payload") ?? ""));
  } catch {
    return { ok: false, message: "Could not read the form. Reload the page and try again." };
  }
  const parsed = projectContentSchema.safeParse(raw);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    return { ok: false, message: issue?.message ?? "Please check the form." };
  }
  const c = parsed.data;

  await getDb().project.update({
    where: { id: projectId },
    data: {
      title: c.title,
      summary: c.summary,
      question: c.question,
      statusLabel: c.statusLabel,
      areas: c.areas,
      leads: c.leads,
      currentStage: Math.min(c.currentStage, c.stages.length - 1),
      whyItMatters: c.whyItMatters,
      subQuestions: c.subQuestions,
      design: c.design,
      dataSources: c.dataSources,
      approach: c.approach,
      scopes: c.scopes,
      stages: c.stages,
      outputs: c.outputs,
      commitments: c.commitments,
      highlights: c.highlights,
      lastUpdated: new Date(new Date().toISOString().slice(0, 10)),
    },
  });
  // Finished projects are on the public site, which is cached.
  updateTag("projects");
  refresh();
  return { ok: true, message: "Saved." };
}

const statusSchema = z.enum(["planning", "active", "paused", "completed"]);

/**
 * Change a project's status. Admins only, because "completed" publishes the
 * project on the public site as finished work.
 */
export async function setProjectStatus(
  _prev: ActionState,
  formData: FormData,
): Promise<ActionState> {
  const projectId = formId(formData, "projectId");
  const check = await requireTeamRunner(projectId);
  if (!check.allowed) return { ok: false, message: check.error };
  if (!check.access.isAdmin) return { ok: false, message: "Only admins can change the status." };
  const status = statusSchema.safeParse(formData.get("status"));
  if (!status.success) return { ok: false, message: "Choose a status." };

  const labels = {
    planning: "Planning",
    active: "In progress",
    paused: "Paused",
    completed: "Completed",
  } as const;
  await getDb().project.update({
    where: { id: projectId },
    data: { status: status.data, statusLabel: labels[status.data] },
  });
  updateTag("projects");
  refresh();
  return {
    ok: true,
    message:
      status.data === "completed"
        ? "Published: the project now appears on the public site as finished work."
        : "Status saved. The project is visible to its team only.",
  };
}
